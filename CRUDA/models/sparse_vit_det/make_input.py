#!/usr/bin/env python3
"""Writes the input activations of vit.c / vit_baseline.c as C initializer
text: vit_input_b<N>.txt for N = 1, 2, 4, 6, 8 batches of 32 rows x 384.

Each file holds its matrix twice, picked by the preprocessor:
  #ifdef VIT_INPUT_TILED  -- padded 16 x 16 tile order, for vit.c
  #else                   -- row-major, for vit_baseline.c
vit.h chooses the file from VIT_NUM_BATCHES.

The files are nested: the N-batch matrix is the first N batches of the
8-batch one, so batch 0 is the same input in every file.

Values: a real standard deviation of about 1 at 5 fractional bits, i.e.
normal with standard deviation 32, rounded and clipped to -128 .. 127.
Run it again only to change the input; run_vit.py rebuilds the programs.

Usage: python3 make_input.py [--seed 1]
"""

import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "ref"))
import nn_ref as ref  # noqa: E402

BATCH, DIM = 32, 384          # must match vit.h (the programs check the count)
BATCH_COUNTS = [1, 2, 4, 6, 8]


def values(vals):
    lines = []
    for i in range(0, len(vals), 16):
        lines.append(", ".join(f"{v:4d}" for v in vals[i:i + 16]) + ",")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    full = np.round(rng.normal(0, 32, size=(max(BATCH_COUNTS) * BATCH, DIM)))
    full = np.clip(full, -128, 127).astype(np.int64)

    for n in BATCH_COUNTS:
        X = full[:n * BATCH]
        tiled = np.frombuffer(ref.to_tiles(X), dtype=np.int8).tolist()
        with open(os.path.join(HERE, f"vit_input_b{n}.txt"), "w") as f:
            f.write(f"// input X: {n} batch{'es' if n > 1 else ''} x {BATCH} rows = "
                    f"{n * BATCH} x {DIM} int8, seed {args.seed} -- generated by make_input.py\n"
                    "// The same values twice: 16 x 16 tile order when VIT_INPUT_TILED is\n"
                    "// defined (vit.c), row-major otherwise (vit_baseline.c).\n"
                    "#ifdef VIT_INPUT_TILED\n")
            f.write(values(tiled))
            f.write("#else\n")
            f.write(values(X.reshape(-1).tolist()))
            f.write("#endif\n")


if __name__ == "__main__":
    main()
