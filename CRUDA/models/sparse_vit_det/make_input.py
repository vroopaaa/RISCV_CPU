#!/usr/bin/env python3
"""Writes the inputs and weights of vit.c / vit_baseline.c as C initializer
text, each matrix in two layouts:

  input/row_major/<name>.txt    row-major            (vit_baseline.c)
  input/tile_major/<name>.txt   padded 16 x 16 tiles (vit.c): row-major
                                inside a tile, tiles in row-major order

Files (<rows>_<cols> is the matrix size):
  X_<rows>_384.txt    input activations, rows = 32 x 1, 2, 4, 6, 8 batches.
                      Nested: each is the first rows of the 256-row matrix,
                      so batch 0 is the same in every file. vit.h picks one
                      from VIT_NUM_BATCHES.
  Wqkv_384_1152.txt   QKV projection weight, K x N = in x out (Q | K | V
                      column blocks of 384)
  Wo_384_384.txt      attention output projection weight, in x out

  input/exp_table_256.txt   softmax's exp table, 256 uint16 values (a vector
                      has no row/tile order, so it is written once):
                      table[d] = round(2^15 * e^(-d / 16)), for scores with
                      4 fractional bits (softmax.md)

Values (vit_block.md section 5): every matrix is normal with standard
deviation 32, rounded and clipped to int8. X then has 5 fractional bits; the
weights stand for real weights with 9 fractional bits.

Usage: python3 make_input.py [--seed 1]
Run it again only to change the data; run_vit.py rebuilds the programs.
"""

import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "ref"))
import nn_ref as ref  # noqa: E402

BATCH, DIM, QKV = 32, 384, 3 * 384     # must match vit.h (the programs check the counts)
BATCH_COUNTS = [1, 2, 4, 6, 8]


def randn8(rng, shape):
    return np.clip(np.round(rng.normal(0, 32, size=shape)), -128, 127).astype(np.int64)


def write(name, mat, title, seed):
    rows, cols = mat.shape
    layouts = [("row_major", mat.reshape(-1), "row-major"),
               ("tile_major", np.frombuffer(ref.to_tiles(mat), dtype=np.int8),
                "16 x 16 tiles, row-major inside a tile, tiles in row-major order")]
    for folder, vals, how in layouts:
        os.makedirs(os.path.join(HERE, "input", folder), exist_ok=True)
        with open(os.path.join(HERE, "input", folder, f"{name}.txt"), "w") as f:
            f.write(f"// {title}: {rows} x {cols} int8, {how}. "
                    f"Seed {seed}, generated by make_input.py.\n")
            vals = vals.tolist()
            for i in range(0, len(vals), 16):
                f.write(", ".join(f"{v:4d}" for v in vals[i:i + 16]) + ",\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    X = randn8(rng, (max(BATCH_COUNTS) * BATCH, DIM))
    Wqkv = randn8(rng, (DIM, QKV))
    Wo = randn8(rng, (DIM, DIM))          # drawn after Wqkv: the earlier files don't change

    for n in BATCH_COUNTS:
        rows = n * BATCH
        write(f"X_{rows}_{DIM}", X[:rows],
              f"input X, {n} batch{'es' if n > 1 else ''} of {BATCH} rows", args.seed)
    write(f"Wqkv_{DIM}_{QKV}", Wqkv, "QKV projection weight Wqkv, in x out", args.seed)
    write(f"Wo_{DIM}_{DIM}", Wo, "attention output projection weight Wo, in x out", args.seed)

    table = ref.exp_table(1 / 16).tolist()
    with open(os.path.join(HERE, "input", "exp_table_256.txt"), "w") as f:
        f.write("// softmax exp table: table[d] = round(2^15 * e^(-d / 16)), d = 0 .. 255, "
                "uint16. Generated by make_input.py.\n")
        for i in range(0, 256, 16):
            f.write(", ".join(f"{v:5d}" for v in table[i:i + 16]) + ",\n")


if __name__ == "__main__":
    main()
