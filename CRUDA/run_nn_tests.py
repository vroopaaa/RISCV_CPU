    add("views", 20, 40, 24, x_t0=1, x_extra=2, y_t0=1, y_extra=1)
    add("saturate +127", 16, 33, 16, fill="sat_pos", shift=0, bias=False)
    add("saturate -128", 16, 33, 16, fill="sat_neg", shift=0, bias=False)
    add("rounding, shift 1", 16, 1, 16, fill="rounding", shift=1, bias_range=(-8, 8))
    add("rounding, shift 2", 16, 1, 16, fill="rounding", shift=2, bias_range=(-8, 8))
