# GEMM -- docs/design/gemm.md
# ---------------------------------------------------------------------

def gemm_cases(large):
    c = []
    add = lambda name, M, K, N, **kw: c.append(dict(name=name, M=M, K=K, N=N, **kw))
    add("one element", 1, 1, 1)
    add("one full tile", 16, 16, 16)
    add("edges everywhere", 17, 33, 5)
    add("multi-tile exact", 48, 64, 32)
    add("K = 1", 20, 1, 20)
    add("long K", 8, 300, 24)
    add("no bias", 17, 33, 5, bias=False)
    add("edge padding, large bias", 5, 16, 3, bias_range=(10**5, 10**6))
    add("views", 20, 40, 24, x_t0=1, x_extra=2, y_t0=1, y_extra=1)
    add("saturate +127", 16, 33, 16, fill="sat_pos", shift=0, bias=False)
    add("saturate -128", 16, 33, 16, fill="sat_neg", shift=0, bias=False)
    add("rounding, shift 1", 16, 1, 16, fill="rounding", shift=1, bias_range=(-8, 8))
    add("rounding, shift 2", 16, 1, 16, fill="rounding", shift=2, bias_range=(-8, 8))
    add("shift 0", 9, 7, 11, shift=0)
    add("shift 31", 9, 7, 11, shift=31)
    add("invalid: M = 0", 0, 16, 16, ret=-1)
    add("invalid: X misaligned", 16, 16, 16, x_misalign=1, ret=-1)
    add("invalid: ldt_x too small", 16, 33, 16, ldt_x_delta=-1, ret=-1)
    add("invalid: shift 32", 16, 16, 16, shift=32, ret=-1)
    if large:
        add("large 256x512x512", 256, 512, 512)
        add("large 128x1536x384", 128, 1536, 384)
        add("large 1024x64x1024", 1024, 64, 1024)
    return c


def gemm_generate(case, rng):
    M, K, N = case["M"], case["K"], case["N"]
    rows = max(M, 1)
    fill = case.get("fill", "random")
    if fill == "random":
        X = rng.integers(-128, 128, size=(rows, K))
        W = rng.integers(-128, 128, size=(K, N))
    elif fill == "sat_pos":
        X, W = np.full((rows, K), -128), np.full((K, N), -128)
    elif fill == "sat_neg":
        X, W = np.full((rows, K), -128), np.full((K, N), 127)
    elif fill == "rounding":   # K = 1: acc = x * w + bias walks through odd/even values
        X = (np.arange(rows * K).reshape(rows, K) % 16) - 8
        W = 1 + (np.arange(K * N).reshape(K, N) % 3)
    shift = case.get("shift")
    if shift is None:
        shift = max(0, round(math.log2(math.sqrt(K) * 85)))
    bias = None
    if case.get("bias", True):
        bscale = 1 << (min(shift, 20) + 6)   # about the size of the accumulator; stays in int32
        lo, hi = case.get("bias_range", (-bscale, bscale))
        bias = rng.integers(lo, hi, size=N)

    Mt, Kt, Nt = ref.pad16(rows) // TILE, ref.pad16(K) // TILE, ref.pad16(N) // TILE
    x_t0, y_t0 = case.get("x_t0", 0), case.get("y_t0", 0)
    ldt_x = x_t0 + Kt + case.get("x_extra", 0)
    ldt_y = y_t0 + Nt + case.get("y_extra", 0)

    d = Data()
    junk = np.random.default_rng(rng.integers(1 << 30) + JUNK_SEED_OFFSET)
    xg = junk.integers(-128, 128, size=(Mt, ldt_x, TILE, TILE))   # junk outside the view
    place(xg, X, x_t0)
    x_off = d.add(grid_bytes(xg)) + x_t0 * TILE_BYTES + case.get("x_misalign", 0)
    w_off = d.add(ref.to_tiles(W))
    b_off = 0
    if bias is not None:
        padded = np.zeros(ref.pad16(N), dtype=np.int64)
        padded[:N] = bias
        b_off = d.add(padded.astype("<i4").tobytes())
    yg = tile_grid(rows, ldt_y, POISON)
    y_buf_off = d.add(grid_bytes(yg) + bytes([POISON]) * GUARD_BYTES)

    d.define("X_OFF", x_off)
    d.define("LDT_X", ldt_x + case.get("ldt_x_delta", 0))
    d.define("W_OFF", w_off)
    d.define("LDT_W", Nt)
    d.define("HAS_BIAS", 1 if bias is not None else 0)
    d.define("BIAS_OFF", b_off)
    d.define("Y_OFF", y_buf_off + y_t0 * TILE_BYTES)
    d.define("LDT_Y", ldt_y)
    d.define("GEMM_M", f"{M}u")
    d.define("GEMM_K", f"{K}u")
    d.define("GEMM_N", f"{N}u")
    d.define("GEMM_SHIFT", f"{shift}u")

    expected = yg.copy()
    ret = case.get("ret", 0)
    if ret == 0:
        place(expected, ref.nn_gemm(X, W, bias, shift), y_t0)
    expected_bytes = grid_bytes(expected) + bytes([POISON]) * GUARD_BYTES
    budget = 2_000_000 + Mt * Nt * (Kt * 40 + 200)
    layout = dict(rows=rows, ldt=ldt_y, t0=y_t0, M=M, N=N, tiles=Mt * ldt_y)
    return d, y_buf_off, expected_bytes, ret, budget, layout


def describe_byte(i, layout):
    """Which part of the output buffer byte i belongs to."""
    if i >= layout["tiles"] * TILE_BYTES:
        return f"guard byte {i - layout['tiles'] * TILE_BYTES}"
    t, within = divmod(i, TILE_BYTES)
    tr, tc = divmod(t, layout["ldt"])
    r, c = tr * TILE + within // TILE, (tc - layout["t0"]) * TILE + within % TILE
    if tc < layout["t0"] or c >= ref.pad16(layout["N"]):
        return f"tile ({tr}, {tc}) outside the output view"
    if r >= layout["M"] or c >= layout["N"]:
        return f"padding element ({r}, {c})"
    return f"element ({r}, {c})"


# ---------------------------------------------------------------------

LEGOS = {
    "gemm": dict(cases=gemm_cases, generate=gemm_generate,
                 test_c=os.path.join(TESTS, "t_gemm.c"),
                 kernels=[os.path.join(KERNELS, "gemm.c")]),
}


def run_lego(lego, large, seed, opt):
    spec = LEGOS[lego]
    passed = failed = 0
    for idx, case in enumerate(spec["cases"](large)):
        rng = np.random.default_rng([seed, idx])
        d, dump_off, expected, ret, budget, layout = spec["generate"](case, rng)
        case_dir = os.path.join(BUILD_DIR, lego, f"case{idx:02d}")
        d.write(case_dir)
        binf, syms = build(case_dir, spec["test_c"], spec["kernels"], opt)
        dump_base = syms["nn_data"] + dump_off
        results = []
        ok = True
        for mode, width in [("scalar", 0)] + [("superscalar", w) for w in SUPERSCALAR_WIDTHS]:
            tag = "scalar" if mode == "scalar" else f"w{width}"
            dump_path = os.path.join(case_dir, f"dump_{tag}.txt")
            a0, cycles, actual, stderr = simulate(binf, budget, dump_base, len(expected),
                                                  dump_path, mode, width)
            problems = []
            if cycles >= budget:
                problems.append(f"did not halt within {budget} cycles")
            if a0 != (ret & 0xFFFFFFFF):
                problems.append(f"returned {a0 - (1 << 32) if a0 >= 1 << 31 else a0}, expected {ret}")
            if stderr.strip():
                problems.append("stderr: " + stderr.strip().splitlines()[0])
            if actual != expected:
                bad = [i for i in range(len(expected)) if i >= len(actual) or actual[i] != expected[i]]
                i = bad[0]
                got = actual[i] if i < len(actual) else None
                to_s8 = lambda b: b - 256 if b is not None and b >= 128 else b
                problems.append(f"{len(bad)} bytes differ; first: {describe_byte(i, layout)} "
                                f"expected {to_s8(expected[i])}, got {to_s8(got)}")
            if problems:
                ok = False
                print(f"FAIL  {lego}: {case['name']} [{tag}]")
                for p in problems:
                    print(f"        {p}")
            results.append(f"{tag} {cycles:,}")
        if ok:
            passed += 1
            print(f"PASS  {lego}: {case['name']}  (cycles: {', '.join(results)})")
        else:
            failed += 1
    return passed, failed


def main():
    ap = argparse.ArgumentParser(description="Run the lego library tests on the RSVP emulator.")
    ap.add_argument("--lego", choices=sorted(LEGOS), action="append",
                    help="lego(s) to test (default: all)")
    ap.add_argument("--large", action="store_true", help="also run the large shapes (slow)")
    ap.add_argument("--seed", type=int, default=1, help="RNG seed (default 1)")
    ap.add_argument("--opt", default="O2", help="optimisation level for host/NPU code (default O2)")
    args = ap.parse_args()

    run(["make", "build/run_test"], cwd=os.path.join(RSVP, "32I"))
    total_pass = total_fail = 0
    for lego in args.lego or sorted(LEGOS):
        p, f = run_lego(lego, args.large, args.seed, args.opt)
        total_pass += p
        total_fail += f
    print(f"\n{total_pass} passed, {total_fail} failed")
    print("ALL TESTS PASSED" if total_fail == 0 else "SOME TESTS FAILED")
    sys.exit(0 if total_fail == 0 else 1)


if __name__ == "__main__":
    main()
