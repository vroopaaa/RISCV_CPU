#!/usr/bin/env python3
"""Lego library test driver -- docs/design/00-overview.md section 7.

For every test case of a lego this script:
  1. generates seeded random inputs in Python, lays them out in the padded
     tile layout (ref/nn_ref.py's to_tiles) and writes them, together with a
     poisoned output buffer and a poisoned guard region after it, into
     build/<case>/data.bin; data.h gets each tensor's offset plus the call's
     parameters, data.s pulls data.bin in with .incbin;
  2. builds 32I's start.s + tests/t_<lego>.c + the lego's kernel file +
     data.s (-O2 by default) against SparseViT/link.ld;
  3. runs it on 32I/build/run_test -- scalar, and superscalar at issue widths
     1/2/4/10 -- dumping the output buffer and its guard region;
  4. checks a0 (the wrapper's return value), the real output elements
     bit-exact against ref/nn_ref.py, zero padding, untouched poison outside
     the output view and in the guard region, and an empty stderr.

Usage:
  python3 run_nn_tests.py                 # every lego, default shapes
  python3 run_nn_tests.py --lego gemm     # one lego
  python3 run_nn_tests.py --large         # also the large shapes (slow)
  python3 run_nn_tests.py --seed 7 --opt O0

Exit code 0 if everything passed, 1 otherwise.
"""

import argparse
import math
import os
import re
import subprocess
import sys

import numpy as np

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(SCRIPT_DIR, "ref"))
import nn_ref as ref  # noqa: E402

RSVP = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
RUN_TEST = os.path.join(RSVP, "32I", "build", "run_test")
START_S = os.path.join(RSVP, "32I", "tests", "python", "start.s")
NPU_INC = os.path.join(RSVP, "32I", "tests", "npu")
INCLUDE = os.path.join(SCRIPT_DIR, "include")
KERNELS = os.path.join(SCRIPT_DIR, "kernels")
TESTS = os.path.join(SCRIPT_DIR, "tests")
LINK_LD = os.path.join(SCRIPT_DIR, "link.ld")
BUILD_DIR = os.path.join(SCRIPT_DIR, "build")

CC = "riscv64-unknown-elf-gcc"
OBJCOPY = "riscv64-unknown-elf-objcopy"
NM = "riscv64-unknown-elf-nm"
CFLAGS = ["-march=rv32im", "-mabi=ilp32", "-nostdlib", "-nostartfiles", "-ffreestanding"]
SUPERSCALAR_WIDTHS = [1, 2, 4, 10]

TILE, TILE_BYTES = ref.TILE, ref.TILE_BYTES
POISON = 0x5A          # fills output buffers and guard regions before a run
JUNK_SEED_OFFSET = 1000
GUARD_BYTES = TILE_BYTES


def run(cmd, cwd=None):
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd)
    if r.returncode != 0:
        raise RuntimeError(f"command failed: {' '.join(cmd)}\n{r.stdout}\n{r.stderr}")
    return r


# ---------------------------------------------------------------------
# Test data: data.bin + data.h + data.s
# ---------------------------------------------------------------------

class Data:
    """Accumulates tensors into one block (each 256-byte aligned) and the
    #defines t_<lego>.c reads."""

    def __init__(self):
        self.buf = bytearray()
        self.defines = []

    def add(self, data):
        while len(self.buf) % TILE_BYTES:
            self.buf.append(0)
        off = len(self.buf)
        self.buf += data
        return off

    def define(self, name, value):
        self.defines.append((name, value))

    def write(self, case_dir):
        os.makedirs(case_dir, exist_ok=True)
        bin_path = os.path.join(case_dir, "data.bin")
        with open(bin_path, "wb") as f:
            f.write(self.buf)
        with open(os.path.join(case_dir, "data.h"), "w") as f:
            f.write("// generated by run_nn_tests.py\n")
            for name, value in self.defines:
                f.write(f"#define {name} {value}\n")
        with open(os.path.join(case_dir, "data.s"), "w") as f:
            f.write("    .section .data\n    .balign 256\n    .globl nn_data\n"
                    f"nn_data:\n    .incbin \"{bin_path}\"\n")


def tile_grid(rows, ldt, fill):
    """A (pad16(rows)/16) x ldt grid of tiles, every byte = fill."""
    return np.full((ref.pad16(rows) // TILE, ldt, TILE, TILE), fill, dtype=np.int64)


def place(grid, mat, t0):
    """Write mat (row-major, real size) into grid's tile columns t0..,
    including its zero padding."""
    rows, cols = mat.shape
    tc = ref.pad16(cols) // TILE
    tiles = np.frombuffer(ref.to_tiles(mat), dtype=np.int8).reshape(-1, tc, TILE, TILE)
    grid[:tiles.shape[0], t0:t0 + tc] = tiles


def grid_bytes(grid):
    return grid.astype(np.int8).tobytes()


# ---------------------------------------------------------------------
# Build and run
# ---------------------------------------------------------------------

def build(case_dir, test_c, kernel_files, opt):
    elf = os.path.join(case_dir, "prog.elf")
    binf = os.path.join(case_dir, "prog.bin")
    run([CC, *CFLAGS, f"-{opt}", "-I", INCLUDE, "-I", NPU_INC, "-I", case_dir,
         "-T", LINK_LD, "-o", elf, START_S, test_c, *kernel_files,
         os.path.join(case_dir, "data.s")])
    run([OBJCOPY, "-O", "binary", elf, binf])
    syms = {}
    for line in run([NM, elf]).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3:
            syms[parts[2]] = int(parts[0], 16)
    return binf, syms


def simulate(binf, budget, dump_base, dump_size, dump_path, mode, width):
    cmd = [RUN_TEST, binf, str(budget), f"{dump_base:x}", f"{dump_size:x}", dump_path]
    if mode == "superscalar":
        cmd += [mode, str(width)]
    r = run(cmd)
    a0 = int(re.findall(r"x10:\s*0x([0-9a-fA-F]+)", r.stdout)[-1], 16)
    cycles = int(re.findall(r"Cycles:\s*(\d+)", r.stdout)[-1])
    words = []
    with open(dump_path) as f:
        for line in f:
            m = re.match(r"0x[0-9a-fA-F]+:\s*([0-9a-fA-F]+)", line.strip())
            if m:
                words.append(int(m.group(1), 16))
    data = bytearray()
    for w in words:
        data += w.to_bytes(4, "little")
    return a0, cycles, bytes(data[:dump_size]), r.stderr


