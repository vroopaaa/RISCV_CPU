def run_lego(lego, large, seed, opt):
    spec = LEGOS[lego]
    passed = failed = 0
    for idx, case in enumerate(spec["cases"](large)):
        rng = np.random.default_rng([seed, idx])
        d, dump_off, expected, ret, budget, layout = spec["generate"](case, rng)
        case_dir = os.path.join(BUILD_DIR, lego, f"case{idx:02d}")
        d.write(case_dir)
        binf, syms = build(case_dir, spec["test_c"], spec["kernels"], opt, case.get("cflags", []))
        dump_base = syms["nn_data"] + dump_off
        results = []
        ok = True
        modes = [("scalar", 0)]
        if not case.get("scalar_only"):
            modes += [("superscalar", w) for w in SUPERSCALAR_WIDTHS]
        for mode, width in modes:
            tag = "scalar" if mode == "scalar" else f"w{width}"
            dump_path = os.path.join(case_dir, f"dump_{tag}.txt")
            start = case.get("start_cycle", 0)
            a0, cycles, actual, stderr = simulate(binf, budget, dump_base, len(expected),
                                                  dump_path, mode, width, start)
            cycles -= start
            problems = []
            if cycles >= budget:
                problems.append(f"did not halt within {budget} cycles")
            if a0 != (ret & 0xFFFFFFFF):
                problems.append(f"returned {a0 - (1 << 32) if a0 >= 1 << 31 else a0}, expected {ret}")
            if stderr.strip():
                problems.append("stderr: " + stderr.strip().splitlines()[0])
            if actual != expected:
                bad = [i for i in range(len(expected)) if i >= len(actual) or actual[i] != expected[i]]
                i = bad[0]
                got = actual[i] if i < len(actual) else None
                to_s8 = lambda b: b - 256 if b is not None and b >= 128 else b
                problems.append(f"{len(bad)} bytes differ; first: {describe_byte(i, layout)} "
                                f"expected {to_s8(expected[i])}, got {to_s8(got)}")
            if problems:
                ok = False
                print(f"FAIL  {lego}: {case['name']} [{tag}]")
                for p in problems:
                    print(f"        {p}")
            results.append(f"{tag} {cycles:,}")
        if ok:
            passed += 1
            print(f"PASS  {lego}: {case['name']}  (cycles: {', '.join(results)})")
        else:
            failed += 1
    return passed, failed


def main():
    ap = argparse.ArgumentParser(description="Run the lego library tests on the RSVP emulator.")
    ap.add_argument("--lego", choices=sorted(LEGOS), action="append",
                    help="lego(s) to test (default: all)")
    ap.add_argument("--large", action="store_true", help="also run the large shapes (slow)")
    ap.add_argument("--seed", type=int, default=1, help="RNG seed (default 1)")
    ap.add_argument("--opt", default="O2", help="optimisation level for host/NPU code (default O2)")
    args = ap.parse_args()

    run(["make", "build/run_test"], cwd=os.path.join(RSVP, "32I"))
    total_pass = total_fail = 0
    for lego in args.lego or sorted(LEGOS):
        p, f = run_lego(lego, args.large, args.seed, args.opt)
        total_pass += p
        total_fail += f
    print(f"\n{total_pass} passed, {total_fail} failed")
    print("ALL TESTS PASSED" if total_fail == 0 else "SOME TESTS FAILED")
    sys.exit(0 if total_fail == 0 else 1)


if __name__ == "__main__":
    main()
